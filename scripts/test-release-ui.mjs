import { shelfAction, shelfView, shelfSort, shelfVersion } from './shelf-actions.mjs';
/** Smoke-test the production dist through its public import/read/save UI. */
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { preview } from 'vite';
import { readFileSync } from 'node:fs';
import { handleOffset, pageBoundary } from './selection-gestures.mjs';
const version = JSON.parse(readFileSync('package.json', 'utf8')).version;
const server = await preview({ preview: { host: '127.0.0.1', port: 5191, strictPort: true }, logLevel: 'error' });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await context.newPage();
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
try {
  await mkdir('output/playwright', { recursive: true });
  await page.goto('http://127.0.0.1:5191');
  await shelfVersion(page, version);
  await page.getByRole('button', {name:'更多',exact:true}).click();
  await page.getByRole('button').filter({hasText:'关于阅读树'}).click();
  await page.getByText('开发者：朱振坚（公号小二菜园）', {exact:true}).waitFor();
  await page.getByText(/FB2 \/ FB2.ZIP/).first().waitFor();
  await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click();
  await page.screenshot({ path: 'output/playwright/release-' + version + '-shelf.png' });
  console.log('✓ production About panel reports version ' + version + ' and the new shelf edition');
  const bookText = Array.from({ length: 32 }, (_, i) => '第' + i + '段。' + '读书使人心静，思考使人明辨。窗前一卷书，字里行间皆有天地。'.repeat(10)).join(String.fromCharCode(10, 10));
  await page.locator('input[type=file]').first().setInputFiles({ name: '安装包交互验收.txt', mimeType: 'text/plain', buffer: Buffer.from(bookText) });
  const book = page.locator('.cell').filter({ hasText: '安装包交互验收' });
  await book.waitFor(); await book.click();
  await page.waitForFunction(() => document.querySelector('.page-inner p'));
  await page.waitForTimeout(600);
  const point = await page.evaluate(() => {
    const node = document.querySelector('.page-inner p').firstChild;
    const r = document.createRange(); r.setStart(node, 7); r.setEnd(node, 8);
    const b = r.getBoundingClientRect(); return { x: b.left + b.width / 2, y: b.top + b.height / 2 };
  });
  const cdp = await context.newCDPSession(page);
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y, id: 1 }] });
  await touch('touchStart', point.x, point.y); await page.waitForTimeout(650); await touch('touchEnd');
  await page.locator('.reader-selection').waitFor();
  const end = await page.getByRole('button', { name: '拖动选区终点' }).boundingBox();
  const boundary = await pageBoundary(page, 1, await handleOffset(page));
  await touch('touchStart', end.x + 22, end.y + 24); await touch('touchMove', 386, 400);
  await page.waitForTimeout(1000);
  assert.equal(await page.evaluate(() => window.__rtPag.page), 0);
  await touch('touchMove', boundary.inside.x, boundary.inside.y);
  await page.waitForTimeout(800);
  assert.equal(await page.evaluate(() => window.__rtPag.page), 0);
  await touch('touchMove', boundary.outside.x, boundary.outside.y);
  await page.waitForFunction(() => window.__rtPag?.page === 1);
  await page.waitForTimeout(1600);
  assert.equal(await page.evaluate(() => window.__rtPag.page), 1);
  await touch('touchMove', 190, 400); await touch('touchEnd');
  await page.locator('.reader-selection').waitFor();
  assert.ok(!/前选|后选/.test(await page.locator('.reader-selection').textContent()));
  const count = Number((await page.locator('.selection-heading span').textContent()).match(/[0-9]+/)[0]);
  assert.ok(count > 200);
  await page.getByRole('button', { name: '朱砂划线' }).tap();
  await page.locator('.reader-selection').waitFor({ state: 'hidden' });
  await page.reload(); await book.waitFor(); await book.click();
  await page.waitForFunction(() => document.querySelector('mark.hl'));
  const savedText = await page.locator('mark.hl').allTextContents();
  assert.equal(savedText.join('').replace(/\s/g, '').length, count);
  assert.deepEqual(errors, []);
  console.log('✓ production bundle imports a book, selects across pages by touch, saves and restores the exact quote');
  await page.screenshot({ path: 'output/playwright/release-' + version + '-saved.png' });
  await page.evaluate(() => window.readingTreeBack());
  await page.locator('.shelf').waitFor();
  await book.getByRole('button', { name: /管理/ }).click();
  await page.getByRole('button', { name: '移入分类', exact: true }).click();
  await page.getByRole('textbox', { name: '分类名称', exact: true }).fill('验收分类');
  await page.getByRole('button', { name: '新建', exact: true }).click();
  await page.getByText('分类已保存', { exact: true }).waitFor();
  await page.getByRole('button', { name: '移动选中 1 本', exact: true }).click();
  await page.getByText('已整理 1 本书', { exact: true }).waitFor();
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.locator('.m-chips').getByRole('button', { name: '验收分类 1', exact: true }).click();
  await book.getByRole('button', { name: /阅读/ }).click();
  await page.waitForFunction(() => document.querySelector('.page-inner p'));
  await page.waitForTimeout(600);
  // The same entry point is called by the Android Activity.
  assert.equal(await page.evaluate(() => window.readingTreeBack()), 'handled');
  await page.locator('.shelf').waitFor();
  console.log('✓ production book menu creates a category, moves a book and returns from reading through the native-back entry point');
  await book.getByRole('button', { name: /管理/ }).click();
  await page.getByRole('button', {name:'标记已读完',exact:true}).click();
  await book.locator('.cell-sub').filter({hasText:'已读完'}).waitFor();
  await page.reload();await book.locator('.cell-sub').filter({hasText:'已读完'}).waitFor();
  await book.getByRole('button', { name: /管理/ }).click();
  await page.getByRole('button', {name:'标记未读完',exact:true}).click();
  await page.waitForFunction(()=>window.__rtLib.getState().books[0].completed===false);
  console.log('PASS production completion action persists and can be undone');
  assert.deepEqual(errors, []);
} catch (error) {
  await page.screenshot({ path: 'output/playwright/release-failure.png' });
  throw error;
} finally { await browser.close(); await new Promise((resolve) => server.httpServer.close(resolve)); }
