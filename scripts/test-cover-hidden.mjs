  await page.locator('.edit-card input[type=file]').setInputFiles({name:'blue.png',mimeType:'image/png',buffer:Buffer.from(blue,'base64')});
  await page.getByRole('button',{name:'保存书籍信息',exact:true}).click();
  await page.getByRole('dialog',{name:'编辑书籍信息'}).waitFor({state:'hidden'});
  const saved = await page.evaluate(async () => {
    const {platform}=await import('/src/platform/web.ts');
    const cover=await platform.getCover('cover-test');const meta=(await platform.listBooks()).find(b=>b.id==='cover-test');
    await platform.putMeta({...meta,updatedAt:99,cover:'old-stale-bytes'});
    return {cover,meta,after:await platform.getCover('cover-test')};
  });
  assert.ok(saved.cover.startsWith('data:image/jpeg'));assert.equal(saved.after,saved.cover);assert.ok(saved.meta.coverUpdatedAt>100);
  await page.reload();
  await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).locator('img').waitFor();
  assert.equal(await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).locator('img').getAttribute('src'),saved.cover);
  console.log('PASS cover replacement persisted after reload; stale metadata cannot overwrite the new image');
  await page.getByRole('button',{name:'管理《封面测试》',exact:true}).click();
  await page.getByRole('button',{name:'移入隐藏分组',exact:true}).click();
  await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).waitFor({state:'hidden'});
  assert.equal(await page.getByRole('button',{name:'继续阅读《封面测试》'}).count(),0);
  await page.getByLabel('搜索书名或作者').fill('封面测试');
  assert.equal(await page.locator('.cell').count(),0);
  await page.getByLabel('搜索书名或作者').fill('');
  await page.reload();
  assert.equal(await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).count(),0);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'全部分类',exact:false}).click();
  await page.getByRole('dialog',{name:'全部分类'}).getByRole('button',{name:/^隐藏/}).click();
  await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'阅读《普通书籍》',exact:true}).count(),0);
  await page.evaluate(async()=>{
    const {platform}=await import('/src/platform/web.ts');const snapshot=await platform.dumpAll();
    await platform.replaceAll(snapshot.metas,snapshot.contents,snapshot.kv);
    await window.__rtLib.getState().init();
  });
  assert.equal(await page.evaluate(()=>window.__rtLib.getState().books.find(b=>b.id==='cover-test').hidden),true);
  for(const view of ['列表','树架','网格']) { await shelfView(page,view);assert.ok((await page.locator('.shelf-main').textContent()).includes('封面测试')); }
  await page.getByRole('button',{name:'管理《封面测试》',exact:true}).click();
  await page.getByRole('button',{name:'移出隐藏分组',exact:true}).click();
  await page.setViewportSize({width:1100,height:844});
  await page.locator('.side-item').filter({hasText:'全部藏书'}).click();
  await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>window.__rtLib.getState().books.find(b=>b.id==='cover-test').nodeId),'literature');
  console.log('PASS hidden books excluded from home/search/continue, persisted through restart, readable in all hidden views, restored to original category');
  await page.getByRole('button',{name:'管理《封面测试》',exact:true}).click();
  await page.getByRole('button',{name:'编辑信息',exact:true}).click();
  await page.getByRole('button',{name:'清除封面',exact:true}).click();
  await page.getByRole('button',{name:'保存书籍信息',exact:true}).click();
  await page.getByRole('dialog',{name:'编辑书籍信息'}).waitFor({state:'hidden'});
  await page.reload();
  assert.equal(await page.getByRole('button',{name:'阅读《封面测试》',exact:true}).locator('img').count(),0);
  console.log('PASS explicit cover removal persists across reload');
  await shelfAction(page,'批量整理','管理');
  await page.getByLabel('查找待整理书籍').fill('普通书籍');
  await page.locator('.category-book input[type=checkbox]').check();
  await page.getByLabel('移入分类',{exact:true}).selectOption('__hidden');
  await page.getByRole('button',{name:'移动选中 1 本',exact:true}).click();
  await page.getByText('已整理 1 本书',{exact:true}).waitFor();
  await page.getByRole('button',{name:'完成',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'阅读《普通书籍》',exact:true}).count(),0);
  console.log('PASS hidden flag and cover survive full backup restore; bulk organizing can move books to hidden');
  await page.screenshot({path:'.tmp/cover-hidden-tested.png'});
  assert.deepEqual(errors,[]);
